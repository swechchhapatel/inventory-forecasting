# -----------------------------------------------------------------------
# API KEY AUTH (per-client keys)
# -----------------------------------------------------------------------
# Client keys live in api/api_keys.json (gitignored -- never commit real
# secrets). Format: {"client-name": "secret-key", ...}. Each client gets its
# own key, so access can be revoked for one client (delete its entry, restart
# the server) without breaking any other client.
#
# First-time setup:
#   1. Copy api/api_keys.json.example to api/api_keys.json
#   2. Replace the placeholder values with real random secrets
#   3. Give each client (e.g. the website, an internal tool) its own entry
#
# The API refuses to start if this file is missing or empty -- intentional,
# so it's impossible to accidentally run the API with no authentication.
API_KEYS_PATH = os.environ.get("STORE_STOCK_API_KEYS_PATH", os.path.join(os.path.dirname(__file__), "api_keys.json"))
API_KEYS_JSON_ENV = os.environ.get("STORE_STOCK_API_KEYS_JSON")  # e.g. '{"website": "secret123"}'


def _load_api_keys() -> dict:
    # Prefer an env var (used on hosting platforms like Render, where committing
    # a keys file isn't desired) -- falls back to the local file for local dev.
    if API_KEYS_JSON_ENV:
        try:
            keys = json.loads(API_KEYS_JSON_ENV)
        except json.JSONDecodeError as e:
            raise RuntimeError(f"STORE_STOCK_API_KEYS_JSON env var is not valid JSON: {e}")
    elif os.path.exists(API_KEYS_PATH):
        with open(API_KEYS_PATH) as f:
            try:
                keys = json.load(f)
            except json.JSONDecodeError as e:
                raise RuntimeError(f"API keys file at {API_KEYS_PATH} is not valid JSON: {e}")
    else:
        raise RuntimeError(
            "No API keys found. Either set the STORE_STOCK_API_KEYS_JSON environment "
            "variable, or create api/api_keys.json locally (copy api_keys.json.example)."
        )
    if not keys or not isinstance(keys, dict):
        raise RuntimeError("API keys are empty or malformed. Expected: {\"client-name\": \"secret-key\", ...}")
    return keys


API_KEYS = _load_api_keys()
_KEY_TO_CLIENT = {v: k for k, v in API_KEYS.items()}  # reverse lookup: key -> client_name

_api_key_header = APIKeyHeader(name="X-API-Key", auto_error=False)


def require_api_key(provided_key: str = Security(_api_key_header)) -> str:
    """Dependency that protects an endpoint behind a per-client API key.
    Returns the calling client's name (from api_keys.json) on success, so
    endpoints/logs can identify who made the request. Uses constant-time
    comparison against every known key to avoid leaking which key (if any)
    was close to correct via timing."""
    if provided_key:
        for known_key, client_name in _KEY_TO_CLIENT.items():
            if secrets.compare_digest(provided_key, known_key):
                return client_name
    raise HTTPException(
        status_code=401,
        detail="Missing or invalid API key. Send it in the 'X-API-Key' header.",
    )


