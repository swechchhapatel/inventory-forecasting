@lru_cache(maxsize=1)
def get_model():
    import xgboost as xgb
    path = xgb.XGBRegressor()
    path.load_model(os.path.join(ARTIFACT_DIR, "xgb_demand_model.json"))
    if not os.path.exists(path):
        raise RuntimeError(f"Model artifact not found at {path}")
    return joblib.load(path)


@lru_cache(maxsize=1)
def get_encoders():
    return joblib.load(os.path.join(ARTIFACT_DIR, "label_encoders.pkl"))


@lru_cache(maxsize=1)
def get_feature_cols():
    with open(os.path.join(ARTIFACT_DIR, "feature_cols.json")) as f:
        return json.load(f)


@lru_cache(maxsize=1)
def get_metrics():
    path = os.path.join(ARTIFACT_DIR, "metrics.json")
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return {}


@lru_cache(maxsize=1)
def get_feature_importance():
    path = os.path.join(ARTIFACT_DIR, "feature_importance.csv")
    if os.path.exists(path):
        return pd.read_csv(path).head(10).to_dict(orient="records")
    return None


@lru_cache(maxsize=1)
def get_historical():
    path = os.path.join(ARTIFACT_DIR, "historical_engineered.parquet")
    if os.path.exists(path):
        return pd.read_parquet(path)
    return None


def get_trend_direction(demand_trend, threshold: float = 1.0) -> str:
    if pd.isna(demand_trend):
        return "flat"
    if demand_trend > threshold:
        return "up"
    if demand_trend < -threshold:
        return "down"
    return "flat"


def run_full_pipeline(raw_df: pd.DataFrame) -> pd.DataFrame:
    """Shared pipeline: bootstrap history -> engineer features -> encode -> predict.
    Same logic the Streamlit app used, now reused by the API."""
    model = get_model()
    encoders = get_encoders()
    feature_cols = get_feature_cols()
    historical_df = get_historical()

    if historical_df is not None:
        combined_raw = bootstrap_history(raw_df, historical_df)
    else:
        combined_raw = raw_df.copy()

    engineered = engineer_features(combined_raw)
    encoded = encode_with_saved_encoders(engineered, encoders)
    preds = predict_demand(model, encoded, feature_cols)
    encoded["Predicted_Demand"] = preds

    upload_keys = raw_df[GROUP_COLS + [DATE_COL]].copy()
    upload_keys[DATE_COL] = pd.to_datetime(upload_keys[DATE_COL])
    encoded[DATE_COL] = pd.to_datetime(encoded[DATE_COL])
    result = encoded.merge(upload_keys, on=GROUP_COLS + [DATE_COL], how="inner")
    return result


def build_item_forecasts(alerts_df: pd.DataFrame) -> list:
    items = []
    for _, row in alerts_df.iterrows():
        trend_dir = get_trend_direction(row.get("demand_trend", 0))
        days_left = row["days_of_stock_left"]
        items.append(ItemForecast(
            store_id=str(row["Store ID"]),
            product_id=str(row["Product ID"]),
            category=row.get("Category"),
            region=row.get("Region"),
            inventory_level=float(row["Inventory Level"]),
            forecasted_daily_demand=round(float(row["Predicted_Demand"]), 2),
            days_of_stock_left=float(days_left) if np.isfinite(days_left) else 999.0,
            reorder_point_units=round(float(row["reorder_point_units"]), 2),
            recommended_order_qty=int(row["recommended_order_qty"]),
            alert_level=row["alert_level"],
            trend=trend_dir,
        ))
    return items


