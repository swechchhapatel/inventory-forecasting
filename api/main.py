@app.get("/health", tags=["System"])
def health_check():
    """Basic liveness check -- confirms the API is up and the model artifacts loaded."""
    try:
        get_model()
        model_ready = True
    except Exception as e:
        model_ready = False
    return {"status": "ok" if model_ready else "degraded", "model_loaded": model_ready}


@app.get("/schema", response_model=SchemaResponse, tags=["System"])
def get_required_schema():
    """Returns the required CSV/JSON columns, so client apps (e.g. the website's
    upload form) can validate data before sending it."""
    return SchemaResponse(
        required_columns=REQUIRED_COLUMNS,
        example_row=SalesRecord.Config.json_schema_extra["example"],
    )


@app.get("/model/info", response_model=ModelInfo, tags=["System"])
def model_info(client: str = Depends(require_api_key)):
    """Model accuracy metrics and top feature importances, for an internal
    monitoring/admin dashboard."""
    logger.info(f"/model/info called by client '{client}'")
    metrics = get_metrics()
    return ModelInfo(
        mae=metrics.get("mae"),
        rmse=metrics.get("rmse"),
        mape=metrics.get("mape"),
        r2=metrics.get("r2"),
        top_features=get_feature_importance(),
    )


@app.post("/forecast", response_model=ForecastResponse, tags=["Forecasting"])
async def forecast_from_csv(
    file: UploadFile = File(..., description="CSV file matching the required schema (see /schema)"),
    lead_time_days: int = Query(7, ge=1, le=60),
    safety_stock_days: int = Query(3, ge=0, le=30),
    critical_days_threshold: float = Query(3, ge=0),
    warning_days_threshold: float = Query(7, ge=0),
    client: str = Depends(require_api_key),
):
    """
    Upload a CSV of sales/inventory data and receive a forecast + restock alert
    for every store-item combination in the file.

    This is the primary endpoint for the website integration: the frontend
    uploads a store's exported sales CSV and gets back a ranked restock list.
    """
    logger.info(f"/forecast called by client '{client}', file='{file.filename}'")

    if not file.filename.lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="File must be a .csv")

    try:
        contents = await file.read()
        raw_df = pd.read_csv(io.BytesIO(contents))
        raw_df.columns = [c.strip() for c in raw_df.columns]
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Could not parse CSV: {e}")

    missing_cols = [c for c in REQUIRED_COLUMNS if c not in raw_df.columns]
    if missing_cols:
        raise HTTPException(
            status_code=422,
            detail=f"Missing required columns: {missing_cols}. See /schema for the full list.",
        )

    try:
        result = run_full_pipeline(raw_df)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Forecasting failed: {e}")

    latest = (
        result.sort_values(DATE_COL)
        .groupby(GROUP_COLS, as_index=False)
        .last()
    )
    alerts = generate_alerts(
        latest,
        lead_time_days=lead_time_days,
        safety_stock_days=safety_stock_days,
        critical_days_threshold=critical_days_threshold,
        warning_days_threshold=warning_days_threshold,
    )

    items = build_item_forecasts(alerts)
    return ForecastResponse(
        n_items=len(items),
        n_critical=sum(1 for i in items if i.alert_level == "Critical"),
        n_warning=sum(1 for i in items if i.alert_level == "Warning"),
        n_ok=sum(1 for i in items if i.alert_level == "OK"),
        n_overstock=sum(1 for i in items if i.alert_level == "Overstock"),
        items=items,
    )


@app.post("/forecast/records", response_model=ForecastResponse, tags=["Forecasting"])
async def forecast_from_records(payload: ForecastRecordsRequest, client: str = Depends(require_api_key)):
    """
    JSON alternative to /forecast, for when the website already holds the data
    in its own database and wants to send it directly without a CSV round-trip.

    Request body shape:
        {
          "records": [ {..SalesRecord fields..}, ... ],
          "settings": { "lead_time_days": 7, "safety_stock_days": 3, ... }   # optional
        }
    """
    logger.info(f"/forecast/records called by client '{client}', n_records={len(payload.records)}")
    records = payload.records
    settings = payload.settings
    if not records:
        raise HTTPException(status_code=400, detail="No records provided")

    raw_df = pd.DataFrame([r.dict(by_alias=True) for r in records])

    try:
        result = run_full_pipeline(raw_df)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Forecasting failed: {e}")

    latest = (
        result.sort_values(DATE_COL)
        .groupby(GROUP_COLS, as_index=False)
        .last()
    )
    alerts = generate_alerts(
        latest,
        lead_time_days=settings.lead_time_days,
        safety_stock_days=settings.safety_stock_days,
        critical_days_threshold=settings.critical_days_threshold,
        warning_days_threshold=settings.warning_days_threshold,
    )

    items = build_item_forecasts(alerts)
    return ForecastResponse(
        n_items=len(items),
        n_critical=sum(1 for i in items if i.alert_level == "Critical"),
        n_warning=sum(1 for i in items if i.alert_level == "Warning"),
        n_ok=sum(1 for i in items if i.alert_level == "OK"),
        n_overstock=sum(1 for i in items if i.alert_level == "Overstock"),
        items=items,
    )


